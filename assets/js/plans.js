// лестница: прямой марш (I) или два марша с площадкой (U)
function drawStair(g, s) {
  const [x0, y0, x1, y1] = s.r;
  const sg = el('g', { class: s.lvl === 2 ? 'pl-stair pl-stair--up' : 'pl-stair' }, g);
  el('rect', { x: x0, y: y0, width: f3(x1 - x0), height: f3(y1 - y0), class: 'pl-st-box' }, sg);
  const alongY = s.go === 'n' || s.go === 's';
  const dir = s.go === 's' || s.go === 'e' ? 1 : -1;
  const [a0, a1] = alongY ? [y0, y1] : [x0, x1];
  const [b0, b1] = alongY ? [x0, x1] : [y0, y1];
  const P = (a, b) => (alongY ? [b, a] : [a, b]);
  const flights = [];
  if (s.kind === 'U') {
    const mid = (b0 + b1) / 2, gap = 0.05;
    const first = (s.side === 'w' || s.side === 'n') ? [b0, mid - gap] : [mid + gap, b1];
    const second = (s.side === 'w' || s.side === 'n') ? [mid + gap, b1] : [b0, mid - gap];
    const start = dir > 0 ? a0 : a1, landEdge = dir > 0 ? a1 - s.land : a0 + s.land;
    flights.push({ b: first, from: start, to: landEdge }, { b: second, from: landEdge, to: start });
    el('line', { x1: f3(P(Math.min(start, landEdge), mid)[0]), y1: f3(P(Math.min(start, landEdge), mid)[1]), x2: f3(P(Math.max(start, landEdge), mid)[0]), y2: f3(P(Math.max(start, landEdge), mid)[1]), class: 'pl-st-line' }, sg);
    el('line', { x1: f3(P(landEdge, b0)[0]), y1: f3(P(landEdge, b0)[1]), x2: f3(P(landEdge, b1)[0]), y2: f3(P(landEdge, b1)[1]), class: 'pl-st-line' }, sg);
  } else {
    flights.push({ b: [b0, b1], from: dir > 0 ? a0 : a1, to: dir > 0 ? a1 : a0 });
  }
  for (const fl of flights) {
    const n = s.n, step = (fl.to - fl.from) / n;
    for (let i = 1; i < n; i++) {
      const a = fl.from + step * i, p1 = P(a, fl.b[0]), p2 = P(a, fl.b[1]);
      el('line', { x1: f3(p1[0]), y1: f3(p1[1]), x2: f3(p2[0]), y2: f3(p2[1]), class: 'pl-st-line' }, sg);
    }
  }
  // стрелка подъёма
  const path = [];
  const f0 = flights[0], st0 = (f0.to - f0.from) / s.n, bc0 = (f0.b[0] + f0.b[1]) / 2;
  path.push(P(f0.from + st0 * 0.5, bc0));
  if (s.kind === 'U') {
    const f1 = flights[1], bc1 = (f1.b[0] + f1.b[1]) / 2, la = f0.to + Math.sign(st0) * s.land / 2;
    path.push(P(la, bc0), P(la, bc1), P(f1.to + st0 * 0.6, bc1));
  } else path.push(P(f0.to - st0 * 0.6, bc0));
  const d = 'M' + path.map(([x, y]) => `${f3(x)} ${f3(y)}`).join('L');
  el('path', { d, class: 'pl-st-arrow' }, sg);
  el('circle', { cx: f3(path[0][0]), cy: f3(path[0][1]), r: 0.07, class: 'pl-st-dot' }, sg);
  const [ex, ey] = path[path.length - 1], [px, py] = path[path.length - 2];
  const L = Math.hypot(ex - px, ey - py), ux = (ex - px) / L, uy = (ey - py) / L;
  el('path', { d: `M${f3(ex - ux * 0.32 - uy * 0.14)} ${f3(ey - uy * 0.32 + ux * 0.14)}L${f3(ex)} ${f3(ey)}L${f3(ex - ux * 0.32 + uy * 0.14)} ${f3(ey - uy * 0.32 - ux * 0.14)}`, class: 'pl-st-arrow' }, sg);
  if (s.lvl === 2) el('rect', { x: f3(x0 + 0.03), y: f3(y0 + 0.03), width: f3(x1 - x0 - 0.06), height: f3(y1 - y0 - 0.06), class: 'pl-void-edge' }, sg);
}

// размерная линия: a, b концы по габариту, at положение линии
function drawDim(g, labels, a, b, axis, at, label) {
  const tick = 0.18;
  if (axis === 'x') {
    el('line', { x1: a - 0.25, y1: at, x2: b + 0.25, y2: at, class: 'pl-dim' }, g);
    for (const x of [a, b]) el('line', { x1: f3(x - tick), y1: f3(at + tick), x2: f3(x + tick), y2: f3(at - tick), class: 'pl-dim pl-dim--tick' }, g);
    labels.push({ x: (a + b) / 2, y: at, ang: 0, t: label, cls: 'pl-dimt' });
  } else {
    el('line', { x1: at, y1: a - 0.25, x2: at, y2: b + 0.25, class: 'pl-dim' }, g);
    for (const y of [a, b]) el('line', { x1: f3(at - tick), y1: f3(y + tick), x2: f3(at + tick), y2: f3(y - tick), class: 'pl-dim pl-dim--tick' }, g);
    labels.push({ x: at, y: (a + b) / 2, ang: -90, t: label, cls: 'pl-dimt' });
  }
}
function drawExt(g, x1, y1, x2, y2) { el('line', { x1: f3(x1), y1: f3(y1), x2: f3(x2), y2: f3(y2), class: 'pl-dim pl-dim--ext' }, g); }

let uid = 0;

export function renderPlan(svg, code, floor = 0, { interactive = true, orient = 'auto', onRoom } = {}) {
  const v = PLANS[code] || PLANS.kvarc;
  const f = v.floors[Math.min(floor, v.floors.length - 1)];
  const prev = state.get(svg);
  if (prev && prev.cleanup) prev.cleanup();

  // ориентация: на узком экране вытянутый план кладём на бок, чтобы был крупнее
  // рамка общая для всех этажей виллы: при переключении этажа дом не прыгает и не меняет масштаб
  const all = v.floors.flatMap((fl) => [...fl.shell.flat(), ...(fl.decks || []).flatMap(d => d.p),
    ...(fl.bay ? bayOuter(fl.bay) : []), ...(fl.pools || []).flatMap(pl => pl.p)]);
  const [bx0, by0, bx1, by1] = bbox(all);
  const wide = (bx1 - bx0) / (by1 - by0);
  const cw = svg.parentElement ? svg.parentElement.clientWidth : 1000;
  const port = orient === 'port' || (orient === 'auto' && cw > 0 && cw < 640 && wide > 1.15);
  const T = port ? ([x, y]) => [-y, x] : ([x, y]) => [x, y];
  const rot = port ? 90 : 0;

  svg.textContent = '';
  svg.classList.add('pl');
  svg.setAttribute('role', interactive ? 'group' : 'img');
  svg.setAttribute('aria-label', `План виллы ${v.name}, ${f.n} этаж, ${fmtArea(f.area)} м²`);
  const id = 'pl' + (++uid);
  const defs = el('defs', {}, svg);
  const patV = el('pattern', { id: id + 'v', width: 0.3, height: 1, patternUnits: 'userSpaceOnUse' }, defs);
  el('line', { x1: 0.15, y1: 0, x2: 0.15, y2: 1, class: 'pl-plank' }, patV);
  const patH = el('pattern', { id: id + 'h', width: 1, height: 0.3, patternUnits: 'userSpaceOnUse' }, defs);
  el('line', { x1: 0, y1: 0.15, x2: 1, y2: 0.15, class: 'pl-plank' }, patH);

  const geo = el('g', { class: 'pl-geo', transform: rot ? `rotate(${rot})` : null }, svg);
  const labels = [];

  // настилы
  for (const d of f.decks || []) {
    const dg = el('g', { class: 'pl-deckg', 'data-room': '' }, geo);
    const [dx0, dy0, dx1, dy1] = bbox(d.p);
    const vertPlanks = (dx1 - dx0) < (dy1 - dy0);
    el('polygon', { points: pts(d.p), class: 'pl-deck' }, dg);
    el('polygon', { points: pts(d.p), fill: `url(#${id}${vertPlanks ? 'v' : 'h'})`, class: 'pl-deck-hatch' }, dg);
    d._g = dg;
    labels.push({ room: d, x: d.lab ? d.lab[0] : (dx0 + dx1) / 2, y: d.lab ? d.lab[1] : (dy0 + dy1) / 2, box: [dx0, dy0, dx1, dy1], deck: true });
  }
  // стены: весь контур тёмным, комнаты вырезаются светлым
  for (const p of f.shell) el('polygon', { points: pts(p), class: 'pl-wall' }, geo);
  // проёмы окон, раздвижных дверей и дверей прорезают стены
  const ops = el('g', { class: 'pl-ops' }, geo);
  // комнаты
  const roomsG = el('g', { class: 'pl-rooms' }, geo);
  f.rooms.forEach((rm, i) => {
    const rg = el('g', { class: `pl-room pl-room--${rm.k}`, 'data-i': i }, roomsG);
    for (const p of rm.p) {
      el('polygon', { points: pts(p), class: 'pl-floor' }, rg);
      if (rm.k === 'void') { const [x0, y0, x1, y1] = bbox(p); el('path', { d: `M${x0} ${y0}L${x1} ${y1}M${x1} ${y0}L${x0} ${y1}`, class: 'pl-void-x' }, rg); }
    }
    rm._g = rg;
    const b = bbox(rm.p[0]);
    labels.push({ room: rm, x: rm.lab ? rm.lab[0] : (b[0] + b[2]) / 2, y: rm.lab ? rm.lab[1] : (b[1] + b[3]) / 2, box: rm.box || b });
  });
  for (const w of f.win || []) drawWin(ops, w, false);
  for (const w of f.slide || []) drawWin(ops, w, true);
  geo.appendChild(ops);
  if (f.bay) drawBay(geo, f.bay);
  // мебель и сантехника
  const fur = el('g', { class: 'pl-items' }, geo);
  for (const it of f.items || []) drawItem(fur, it);
  for (const pl of f.pools || []) {
    const [[px0, py0], , [px1, py1]] = pl.p;
    el('rect', { x: px0, y: py0, width: f3(px1 - px0), height: f3(py1 - py0), class: 'pl-pool' }, geo);
    const n = Math.floor((py1 - py0) / 0.9);
    for (let i = 1; i < n; i++) { const yy = py0 + (py1 - py0) * i / n; el('path', { d: `M${f3(px0 + 0.6)} ${f3(yy)}q${f3((px1 - px0 - 1.2) / 4)} -.12 ${f3((px1 - px0 - 1.2) / 2)} 0t${f3((px1 - px0 - 1.2) / 2)} 0`, class: 'pl-ripple' }, geo); }
    if (pl.edge) el('line', { x1: pl.edge[0], y1: pl.edge[1], x2: pl.edge[2], y2: pl.edge[3], class: 'pl-infinity' }, geo);
    labels.push({ room: { n: pl.n, k: 'void' }, x: (px0 + px1) / 2, y: (py0 + py1) / 2, box: [px0, py0, px1, py1] });
  }
  if (f.stair) drawStair(geo, f.stair);
  for (const rl of f.rails || []) el('line', { x1: rl[0], y1: rl[1], x2: rl[2], y2: rl[3], class: 'pl-rail' }, geo);
  const dg = el('g', { class: 'pl-doors' }, geo);
  for (const d of f.doors || []) drawDoor(dg, d);

  // размеры по наружному контуру
  const sb = bbox(f.shell.flat());
  const dimG = el('g', { class: 'pl-dims' }, geo);
  const side = f.dims || 'tl';
  const eb = bbox(v.floors.flatMap(fl => [...fl.shell.flat(), ...(fl.bay ? bayOuter(fl.bay) : [])]));
  const yAt = side.includes('t') ? eb[1] - 1.1 : eb[3] + 1.1;
  const xAt = side.includes('l') ? eb[0] - 1.1 : eb[2] + 1.1;
  const yEdge = side.includes('t') ? sb[1] - 0.25 : sb[3] + 0.25, xEdge = side.includes('l') ? sb[0] - 0.25 : sb[2] + 0.25;
  drawExt(dimG, sb[0], yEdge, sb[0], yAt + (side.includes('t') ? -0.3 : 0.3));
  drawExt(dimG, sb[2], yEdge, sb[2], yAt + (side.includes('t') ? -0.3 : 0.3));
  drawExt(dimG, xEdge, sb[1], xAt + (side.includes('l') ? -0.3 : 0.3), sb[1]);
  drawExt(dimG, xEdge, sb[3], xAt + (side.includes('l') ? -0.3 : 0.3), sb[3]);
  drawDim(dimG, labels, sb[0], sb[2], 'x', yAt, fmtM(sb[2] - sb[0]) + ' м');
  drawDim(dimG, labels, sb[1], sb[3], 'y', xAt, fmtM(sb[3] - sb[1]) + ' м');

  // стрелка севера: в углу, противоположном размерам по горизонтали
  const nx = side.includes('l') ? Math.max(bx1, sb[2]) + 1.4 : Math.min(bx0, sb[0]) - 1.4;
  const ny = side.includes('t') ? eb[1] - 0.6 : eb[3] + 0.6;
  const ng = el('g', { class: 'pl-north', transform: `translate(${f3(nx)} ${f3(ny)}) rotate(${-v.up})` }, geo);
  el('circle', { cx: 0, cy: 0, r: 0.75, class: 'pl-north-ring' }, ng);
  el('path', { d: 'M0 -0.95L0.22 0.35L0 0.18L-0.22 0.35Z', class: 'pl-north-needle' }, ng);
  const na = (-v.up) * Math.PI / 180;
  labels.push({ x: nx + Math.sin(na) * 1.35, y: ny - Math.cos(na) * 1.35, ang: 0, t: 'С', cls: 'pl-northt' });

  // подписи (поверх, не поворачиваются)
  const lab = el('g', { class: 'pl-labels', 'aria-hidden': 'true' }, svg);
  const roomLabels = [];
  for (const L of labels) {
    const [X, Y] = T([L.x, L.y]);
    if (L.room) {
      const g = el('g', { class: 'pl-lb' + (L.deck ? ' pl-lb--deck' : '') + (L.room.k === 'void' ? ' pl-lb--void' : ''), transform: `translate(${f3(X)} ${f3(Y)})` }, lab);
      const nm = el('text', { class: 'pl-name', y: 0 }, g, L.room.n);
      const ar = L.room.k === 'void' ? null : el('text', { class: 'pl-area', y: 0 }, g, fmtArea(L.room.a) + ' м²');
      const bx = L.box; const c1 = T([bx[0], bx[1]]), c2 = T([bx[2], bx[3]]);
      const box = [Math.min(c1[0], c2[0]), Math.min(c1[1], c2[1]), Math.max(c1[0], c2[0]), Math.max(c1[1], c2[1])];
      roomLabels.push({ g, nm, ar, room: L.room, box, X, Y });
      L.room._lb = g;
    } else {
      let ang = L.cls === 'pl-dimt' ? L.ang + rot : 0; if (ang > 90) ang -= 180; if (ang <= -90) ang += 180; if (ang === 90) ang = -90;
      el('text', { class: L.cls, dy: L.cls === 'pl-dimt' ? '-0.5em' : null, transform: `translate(${f3(X)} ${f3(Y)})${ang ? ` rotate(${ang})` : ''}` }, lab, L.t);
    }
  }

  // viewBox по всему нарисованному
  const tb = bbox([...all, [sb[0], yAt - 0.6], [xAt - 0.6, sb[1]], [nx - 1, ny - 1.6], [nx + 1, ny + 1], [sb[2], yAt + 0.6], [xAt + 0.6, sb[3]]].map(T));
  const pad = 0.4;
  const vb = [tb[0] - pad, tb[1] - pad, tb[2] - tb[0] + pad * 2, tb[3] - tb[1] + pad * 2];
  svg.setAttribute('viewBox', vb.map(f3).join(' '));

  // подгонка подписей под реальный размер на экране
  function fit() {
    const w = svg.getBoundingClientRect().width;
    if (!w) return;
    const u = vb[2] / w; // единиц плана в одном css-пикселе
    svg.style.setProperty('--u', u);
    const fsN = 11.5 * u, fsA = 10.5 * u, padX = 6 * u;
    for (const R of roomLabels) {
      const availW = R.box[2] - R.box[0] - padX * 2, availH = R.box[3] - R.box[1] - 4 * u;
      R.nm.textContent = R.room.n;
      R.g.classList.remove('pl-lb--short', 'pl-lb--noarea', 'pl-lb--hide');
      let nw = R.nm.getComputedTextLength ? R.nm.getComputedTextLength() : R.room.n.length * fsN * 0.5;
      if (nw > availW && R.room.s) { R.nm.textContent = R.room.s; R.g.classList.add('pl-lb--short'); nw = R.nm.getComputedTextLength ? R.nm.getComputedTextLength() : R.room.s.length * fsN * 0.5; }
      const twoLines = fsN * 1.15 + fsA * 1.2;
      const showArea = R.ar && availH >= twoLines && (R.ar.getComputedTextLength ? R.ar.getComputedTextLength() : 7 * fsA * 0.5) <= availW;
      if (nw > availW || availH < fsN * 1.2) R.g.classList.add('pl-lb--hide');
      if (!showArea) R.g.classList.add('pl-lb--noarea');
      // имя и площадь: по центру точки подписи, две строки
      if (showArea) { R.nm.setAttribute('y', f3(-fsA * 0.35)); R.ar.setAttribute('y', f3(fsN * 0.95)); }
      else { R.nm.setAttribute('y', f3(fsN * 0.35)); if (R.ar) R.ar.setAttribute('y', f3(fsN * 1.5)); }
    }
  }

  // интерактив: наведение и фокус подсвечивают комнату и дают площадь крупнее
  if (interactive) {
    const fire = (rm) => {
      const detail = rm ? { code: v.code, floor: f.n - 1, name: rm.n, area: rm.a, kind: rm.k } : null;
      if (onRoom) onRoom(detail);
      svg.dispatchEvent(new CustomEvent('pl:room', { detail, bubbles: true }));
    };
    const on = (rm) => { rm._g.classList.add('is-on'); rm._lb && rm._lb.classList.add('is-on'); fire(rm); };
    const off = (rm) => { rm._g.classList.remove('is-on'); rm._lb && rm._lb.classList.remove('is-on'); fire(null); };
    const list = [...f.rooms, ...(f.decks || [])];
    let cur = null;
    for (const rm of list) {
      const g = rm._g;
      g.setAttribute('tabindex', '0');
      g.setAttribute('role', 'button');
      g.setAttribute('aria-label', rm.k === 'void' ? rm.n : `${rm.n}, ${fmtArea(rm.a)} м²${rm.k === 'deck' ? ', не входит в площадь дома' : ''}`);
      const enter = () => { if (cur && cur !== rm) off(cur); cur = rm; on(rm); };
      const leave = () => { if (cur === rm) { off(rm); cur = null; } };
      g.addEventListener('pointerenter', (e) => { if (e.pointerType === 'mouse') enter(); });
      g.addEventListener('pointerleave', (e) => { if (e.pointerType === 'mouse') leave(); });
      g.addEventListener('click', () => { if (cur === rm) leave(); else enter(); });
      g.addEventListener('focus', enter);
      g.addEventListener('blur', leave);
    }
  }

  fit();
  let ro = null;
  if (typeof ResizeObserver !== 'undefined') { ro = new ResizeObserver(() => fit()); ro.observe(svg); }
  if (document.fonts && document.fonts.status !== 'loaded') document.fonts.ready.then(fit);
  let mq = null, mqh = null;
  if (orient === 'auto' && typeof matchMedia !== 'undefined') {
    mq = matchMedia('(max-width: 639px)');
    mqh = () => renderPlan(svg, code, floor, { interactive, orient, onRoom });
    mq.addEventListener('change', mqh);
  }
  state.set(svg, { cleanup() { ro && ro.disconnect(); mq && mq.removeEventListener('change', mqh); } });
  return { area: f.area, rotated: port };
}
