function drawDoor(g, d) {
  const [x0, y0, x1, y1, code] = d;
  el('rect', { x: x0, y: y0, width: f3(x1 - x0), height: f3(y1 - y0), class: 'pl-gap' }, g);
  if (code === 'o') return;
  const vert = (x1 - x0) < (y1 - y0); // стена вертикальная, проём вдоль y
  let hx, hy, lx, ly, ex, ey;
  if (vert) {
    const w = y1 - y0;
    const fx = code[1] === 'r' ? x1 : x0, sgn = code[1] === 'r' ? 1 : -1;
    hy = code[0] === 't' ? y0 : y1; hx = fx;
    lx = hx + sgn * w; ly = hy;
    ex = fx; ey = code[0] === 't' ? y1 : y0;
  } else {
    const w = x1 - x0;
    const fy = code[1] === 'b' ? y1 : y0, sgn = code[1] === 'b' ? 1 : -1;
    hx = code[0] === 'l' ? x0 : x1; hy = fy;
    lx = hx; ly = hy + sgn * w;
    ex = code[0] === 'l' ? x1 : x0; ey = fy;
  }
  const w = Math.hypot(lx - hx, ly - hy);
  // направление обхода дуги: от конца полотна к закрытому положению
  const cross = (lx - hx) * (ey - hy) - (ly - hy) * (ex - hx);
  el('path', { d: `M${f3(lx)} ${f3(ly)}A${f3(w)} ${f3(w)} 0 0 ${cross > 0 ? 1 : 0} ${f3(ex)} ${f3(ey)}`, class: 'pl-swing' }, g);
  el('line', { x1: f3(hx), y1: f3(hy), x2: f3(lx), y2: f3(ly), class: 'pl-leaf' }, g);
}

