for (const code in PLANS) {
  const v = PLANS[code];
  v.code = code;
  v.floors.forEach((f, fi) => {
    f.n = fi + 1;
    for (const rm of f.rooms) rm.a = rm.p.reduce((s, p) => s + polyArea(p), 0);
    // номера как в экспликации: сначала прихожая или холл, дальше в порядке описания
    let no = 0;
    for (const rm of [...f.rooms.filter(r => r.k === 'hall'), ...f.rooms.filter(r => r.k !== 'hall' && r.k !== 'void')]) rm.no = `${fi + 1}.${++no}`;
    for (const d of f.decks || []) d.no = `${fi + 1}.${++no}`;
    for (const h of f.holes || []) f.rooms[h.room].a -= polyArea(h.p);
    for (const d of f.decks || []) { d.k = 'deck'; d.a = polyArea(d.p) - (d.minus ? polyArea(d.minus) : 0); }
    f.area = f.rooms.filter(rm => rm.k !== 'void').reduce((s, rm) => s + rm.a, 0);
  });
  v.calc = v.floors.reduce((s, f) => s + f.area, 0);
}

