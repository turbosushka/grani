const r = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];
function polyArea(p) {
  let s = 0;
  for (let i = 0; i < p.length; i++) { const [a, b] = p[i], [c, d] = p[(i + 1) % p.length]; s += a * d - c * b; }
  return Math.abs(s) / 2;
}
function bbox(pts) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const [x, y] of pts) { if (x < x0) x0 = x; if (y < y0) y0 = y; if (x > x1) x1 = x; if (y > y1) y1 = y; }
  return [x0, y0, x1, y1];
}
// сдвиг ломаной на d в сторону точки c (с митрами в изломах)
function offsetLine(pts, d, c) {
  const segs = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[i + 1];
    const L = Math.hypot(x2 - x1, y2 - y1);
    let nx = -(y2 - y1) / L, ny = (x2 - x1) / L;
    const mx = (x1 + x2) / 2, my = (y1 + y2) / 2;
    if ((c[0] - mx) * nx + (c[1] - my) * ny < 0) { nx = -nx; ny = -ny; }
    segs.push([[x1 + nx * d, y1 + ny * d], [x2 + nx * d, y2 + ny * d]]);
  }
  const out = [segs[0][0]];
  for (let i = 0; i < segs.length - 1; i++) {
    const [p1, p2] = segs[i], [p3, p4] = segs[i + 1];
    const d1x = p2[0] - p1[0], d1y = p2[1] - p1[1], d2x = p4[0] - p3[0], d2y = p4[1] - p3[1];
    const den = d1x * d2y - d1y * d2x;
    if (Math.abs(den) < 1e-9) { out.push(p2); continue; }
    const t = ((p3[0] - p1[0]) * d2y - (p3[1] - p1[1]) * d2x) / den;
    out.push([p1[0] + d1x * t, p1[1] + d1y * t]);
  }
  out.push(segs[segs.length - 1][1]);
  return out;
}
const GL = 0.07; // половина толщины стеклянной полосы

// Кусок комнаты внутри гранёного эркера: от внутренней грани стены до внутренней линии стекла.
function bayPiece(g) {
  const inner = offsetLine(g.pts, GL, g.c);
  const a = g.pts[0], b = g.pts[g.pts.length - 1];
  const v = g.side === 'e' || g.side === 'w';
  return v ? [[g.face, a[1]], ...inner, [g.face, b[1]]] : [[a[0], g.face], ...inner, [b[0], g.face]];
}
// Внешний контур эркера (для настила, который его обходит)
function bayOuter(g) { return offsetLine(g.pts, GL, [2 * g.pts[1][0] - g.c[0], 2 * g.pts[1][1] - g.c[1]]); }
// Настил-прямоугольник, примыкающий к фасаду с эркером: контур обходит стекло снаружи.
function deckAround(x0, y0, x1, y1, g) {
  const o = bayOuter(g), a = g.pts[0], b = g.pts[g.pts.length - 1];
  const TL = [x0, y0], TR = [x1, y0], BR = [x1, y1], BL = [x0, y1];
  let mid;
  if (g.side === 'w') { mid = [[x1, Math.min(a[1], b[1])], ...o.slice().sort((p, q) => p[1] - q[1]), [x1, Math.max(a[1], b[1])]]; return [TL, TR, ...mid, BR, BL]; }
  if (g.side === 'e') { mid = [[x0, Math.max(a[1], b[1])], ...o.slice().sort((p, q) => q[1] - p[1]), [x0, Math.min(a[1], b[1])]]; return [TL, TR, BR, BL, ...mid]; }
  if (g.side === 'n') { mid = [[Math.max(a[0], b[0]), y1], ...o.slice().sort((p, q) => q[0] - p[0]), [Math.min(a[0], b[0]), y1]]; return [TL, TR, BR, ...mid, BL]; }
  mid = [[Math.min(a[0], b[0]), y0], ...o.slice().sort((p, q) => p[0] - q[0]), [Math.max(a[0], b[0]), y0]]; return [TL, ...mid, TR, BR, BL];
}

