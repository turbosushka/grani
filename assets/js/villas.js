// Вилла по коду из адреса (?v=kvarc). Пустой или неверный код → Кварц.
export const villaByCode = (code) => VILLAS.find((v) => v.code === code) || VILLAS[0];

// главный азимут окон: середина сектора
export const azMain = (v) => ((v.az[0] + v.az[1]) / 2) % 360;
// восход или закат по азимуту окон: восточная половина неба (0–180) встречает восход
export const sunSide = (v) => (azMain(v) < 180 ? 'rise' : 'set');

// 1 этаж, 2 этажа, 5 этажей
export function plural(n, one, few, many) {
  const a = Math.abs(n) % 10, b = Math.abs(n) % 100;
  if (a === 1 && b !== 11) return one;
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return few;
  return many;
}
export const bedsWord = (n) => plural(n, 'спальня', 'спальни', 'спален');
export const levelsWord = (n) => plural(n, 'этаж', 'этажа', 'этажей');
export const statusWord = (v) => (v.res ? 'в резерве' : 'в продаже');

// путь к фото: новые кадры вилл лежат в img/villy/, старые кадры v1 (bath, kitchen, pier, view) в img/
const OLD = new Set(['bath', 'kitchen', 'pier', 'view', 'exterior']);
export const imgSrc = (name, m) => `assets/img/${OLD.has(name) ? '' : 'villy/'}${name}${m ? '-m' : ''}.webp`;
// ширина лёгкой (-m) и полной версии кадра, для srcset
